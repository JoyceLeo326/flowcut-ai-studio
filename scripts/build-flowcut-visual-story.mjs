import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { FLOWCUT_VISUAL_PHASES, FLOWCUT_VISUAL_STORIES } from "./flowcut-visual-data.mjs";

const root = process.cwd();
const manifestPath = resolve(root, "mirror-src/assets/story-v3/manifest.json");
const runtimePath = resolve(root, "mirror-src/visual-story-v3.js");
await mkdir(dirname(manifestPath), { recursive: true });

const manifest = {
  project: "flowcut-ai-studio",
  version: 3,
  generatedBy: "OpenAI built-in imagegen, one call per asset",
  imageContract: { format: "webp", width: 768, height: 512, minimumAssets: 50, minimumCoreReachable: 20 },
  assets: FLOWCUT_VISUAL_STORIES,
};

const runtimeStories = FLOWCUT_VISUAL_STORIES.map((story) => `  {
    id: ${JSON.stringify(story.id)},
    src: ${JSON.stringify(`./assets/story-v3/${story.file.split("/").at(-1)}`)},
    phase: ${JSON.stringify(story.phase)},
    phaseLabel: ${JSON.stringify(story.phaseLabel)},
    person: ${JSON.stringify(story.person)},
    situation: ${JSON.stringify(story.situation)},
    action: ${JSON.stringify(story.action)},
    productState: ${JSON.stringify(story.productState)},
    outcome: ${JSON.stringify(story.outcome)},
    alt: ${JSON.stringify(story.alt)},
    coreReachable: ${story.coreReachable ? "true" : "false"},
  }`).join(",\n");

const runtime = `// Generated by scripts/build-flowcut-visual-story.mjs from the exact prompt manifest source.\n` +
  `export const VISUAL_STORY_PHASES_V3 = ${JSON.stringify(FLOWCUT_VISUAL_PHASES, null, 2)};\n\n` +
  `export const VISUAL_STORIES_V3 = [\n${runtimeStories}\n];\n`;

await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`, "utf8");
await writeFile(runtimePath, runtime, "utf8");
console.log(`Prepared ${manifest.assets.length} FlowCut visual story records.`);

